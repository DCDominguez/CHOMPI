#!/usr/bin/env python3
"""Generate the static Choowi workshop's data for GitHub Pages (docs/workshop/).

- editor.js: the editor's control definitions, copied from host/web/app.js (everything before
  its `let token` line), so the local workshop and the site share one list of controls.
- data.js: the chatbot prompt (forge_ai.chat_prompt without the user's words) and the presets,
  all as v8 instruments.
- docs/forge/ILLUSTRATED_MANUAL.html: its panel figures use the phone display's drawing and labels
  (panel-art.js and display-model.js, copied in between its panel-art markers, since the manual must
  stand alone on the card).

tests/test_site.py fails if these files are out of date. Run after changing host/web/app.js's
controls, forge_ai's instructions or the presets:

    python host/build_site.py
"""
import json
from pathlib import Path
import sys

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import forge_ai
import forge_host as host

ROOT = HERE.parent
SITE = ROOT.parents[1] / "docs" / "workshop"
MANUAL = ROOT.parents[1] / "docs" / "forge" / "ILLUSTRATED_MANUAL.html"
MARK = "let token"


def editor_js():
    source = (HERE / "web" / "app.js").read_text(encoding="utf-8")
    head = source[:source.index(MARK)]
    return ("// Generated by host/build_site.py from host/web/app.js (its control definitions). Do not edit here.\n"
            + head)


def data_js():
    probe = "\u0000SOUND\u0000"
    prompt = forge_ai.chat_prompt(probe, "instrument")
    prefix, suffix = prompt.split(probe)
    presets = [host.upgrade_patch(host.load_patch(path), 8) for path in sorted((ROOT / "presets").glob("*.json"))]
    data = {"promptPrefix": prefix, "promptSuffix": suffix, "presets": presets}
    return ("// Generated by host/build_site.py (forge_ai.chat_prompt and presets/*.json as v8). Do not edit here.\n"
            "window.CHOOWI_DATA = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")


def manual_html():
    text = MANUAL.read_text(encoding="utf-8")
    begin, end = text.index("<!-- panel-art:begin"), text.index("<!-- panel-art:end -->")
    head = text[begin:text.index("\n", begin) + 1]
    code = "\n".join((SITE / name).read_text(encoding="utf-8").rstrip() for name in ("panel-art.js", "display-model.js"))
    if "</script" in code: raise ValueError("panel-art / display-model must not contain </script")
    text = text[:begin] + head + "<script>\n" + code + "\n</script>\n" + text[end:]
    return glossary_into(text)


def glossary_into(text):
    """docs/forge/GLOSSARY.md as the manual's Glossary section: headings and "- **Term**: text" items only."""
    import html, re
    source = (MANUAL.parent / "GLOSSARY.md").read_text(encoding="utf-8")
    def inline(s):
        s = html.escape(s, quote=False)
        s = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", s)
        return re.sub(r"\*([^*]+)\*", r"<i>\1</i>", s)
    out, items = [], []
    def flush():
        if items: out.append('<dl class="glossary">' + "".join(items) + "</dl>"); items.clear()
    for line in source.splitlines():
        if line.startswith("## "): flush(); out.append(f"<h3>{html.escape(line[3:])}</h3>")
        elif line.startswith("- **"):
            term, _, rest = line[2:].partition(": ")
            items.append(f"<dt>{inline(term)}</dt><dd>{inline(rest)}</dd>")
        elif line and not line.startswith("#"): flush(); out.append(f'<p class="col">{inline(line)}</p>')
    flush()
    begin, end = text.index("<!-- glossary:begin"), text.index("<!-- glossary:end -->")
    head = text[begin:text.index("\n", begin) + 1]
    return text[:begin] + head + "\n".join(out) + "\n" + text[end:]


def outputs():
    return {SITE / "editor.js": editor_js(), SITE / "data.js": data_js(), MANUAL: manual_html()}


def main():
    SITE.mkdir(parents=True, exist_ok=True)
    for path, text in outputs().items():
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {path} ({len(text):,} characters)")


if __name__ == "__main__":
    main()
